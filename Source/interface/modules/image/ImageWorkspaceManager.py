    def invalidate_model(self):
        """Called on the UI thread after a model load, edit, or operator change."""
        if self._closed:
            return
        self.cancel()
        self._discard_result()
        self._show_original_view = False
        self._model_reference = self._space()
        self._operator = getattr(self._model_reference, "tconorm", None)
        self._sync_space_state()
        self._update_mapping_options()
        self._update_sample_ui()
        self._schedule_render()

    def _change_tconorm(self, operator):
        space = self._space()
        if not getattr(space, "is_granular", False) or space.tconorm == operator:
            return
        if self._saving or (self._worker is not None and self._worker.is_alive()):
            messagebox.showwarning("Process Running", "Cancel the current process before changing the T-conorm.", parent=self.win)
            return
        self.app._set_image_mapping_tconorm(operator)
        # The real mainInterface invalidates the workspace through its shared
        # cache invalidation. A test app or alternative caller may not, so
        # perform a fallback only if that notification has not happened.
        if not self._closed and space.tconorm == operator and self._operator != operator:
            self.invalidate_model()

    def _on_scope_changed(self, _event=None):
        self._show_original_view = False
        self._render()

