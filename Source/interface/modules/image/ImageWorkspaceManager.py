def _roi_box(x1, y1, x2, y2, size):
    """Clip an inclusive user ROI into a PIL half-open crop box."""
    w, h = size
    x0 = max(0, min(w - 1, int(min(x1, x2))))
    y0 = max(0, min(h - 1, int(min(y1, y2))))
    xend = min(w, max(x0 + 1, int(max(x1, x2)) + 1))
    yend = min(h, max(y0 + 1, int(max(y1, y2)) + 1))
    return x0, y0, xend, yend


def _tile_rows(width, target_pixels=110_000):
    return max(1, min(192, target_pixels // max(1, width)))


def _allocate_map(shape, dtype, directory, name, memory_threshold=8_000_000):
    if int(np.prod(shape)) <= memory_threshold:
        return np.empty(shape, dtype=dtype)
    return np.memmap(os.path.join(directory, name), dtype=dtype, mode="w+", shape=shape)


def _publish_export_directory(staged, target, cancelled=None):
    """Commit a complete result folder, preserving any previous export on failure.

    Both directories must be on the same filesystem. Cancellation is honoured
    until the commit begins; once promotion starts we finish or roll back.
    This prevents mixed old/new results and partially overwritten exports.
    """
    staged, target = Path(staged), Path(target)
    if cancelled and cancelled():
        return False
    if target.is_symlink():
        raise ValueError(f"Cannot replace a symbolic link with an analysis directory: {target}")
    if target.exists() and not target.is_dir():
        raise ValueError(f"Cannot replace a file with an analysis directory: {target}")
    backup = None
    if target.exists():
        backup = Path(tempfile.mkdtemp(prefix=".pyfcs_previous_", dir=target.parent))
        backup.rmdir()
        try:
            os.replace(target, backup)
        except Exception:
            # No file inside the existing output has been changed.
            raise
    try:
        os.replace(staged, target)
    except Exception:
        if backup is not None:
            try:
                os.replace(backup, target)
            except Exception as rollback_error:
                raise RuntimeError(
                    f"Could not publish results or restore the previous folder. "
                    f"Previous results are preserved at: {backup}"
                ) from rollback_error
        raise
    if backup is not None:
        try:
            shutil.rmtree(backup)
        except OSError:
            # The newly published results are complete; Windows may still
            # hold a handle to a file from the previous export.
            pass
    return True


def _dispose_mapping_result(result, tempdir):
    """Close disk-backed arrays BEFORE removing scratch files (Windows-safe)."""
    if result is not None:
        for key in ("categories", "granules", "membership"):
            array = result.pop(key, None)
            if isinstance(array, np.memmap):
                # Discarded results need not be flushed. Close the OS handle
                # before unlinking, including on Windows or disk-full errors.
                mapping = getattr(array, "_mmap", None)
                if mapping is not None and not mapping.closed:
                    mapping.close()
    if tempdir is not None:
        tempdir.cleanup()


def compute_full_resolution_mapping(image, manager, space, *, kind="all",
                                    scope=None, selected=None, progress=None,
                                    cancelled=None, directory=None):
    """Map all source pixels or an exact source-pixel ROI by bounded-size tiles.

    `kind`: all or single. `selected`: (category_index, optional granule_index).
    `scope`: PIL-style (left, top, right, bottom) of the source image.
    Returns arrays in ROI-local coordinates; the caller retains the scope.
    The caller owns `directory` until all resulting maps are discarded.
    Does not call Tk or mutate `space`.
    """
    if image is None or space is None:
        raise ValueError("An image and a color space are required.")
    if directory is None or not os.path.isdir(directory):
        raise ValueError("A valid output scratch directory is required.")
    if kind not in ("all", "single"):
        raise ValueError("Unsupported mapping mode.")
    if scope is None:
        scope = (0, 0, *image.size)
    x0, y0, x1, y1 = [int(v) for v in scope]
    if not (0 <= x0 < x1 <= image.width and 0 <= y0 < y1 <= image.height):
        raise ValueError("Processing ROI is outside the image.")
    if kind == "single":
        if selected is None:
            raise ValueError("Select a category or granule first.")
        category, granule = selected
        if not 0 <= int(category) < len(space.get_prototypes()):
            raise ValueError("Selected category is out of range.")
        if granule is not None:
            if not getattr(space, "is_granular", False):
                raise ValueError("The selected color space has no individual granules.")
            if not 0 <= int(granule) < len(space.categories[int(category)].prototypes):
                raise ValueError("Selected granule is out of range.")

    width, height = x1 - x0, y1 - y0
    result = {"scope": (x0, y0, x1, y1), "kind": kind,
              "selected": selected, "covering": bool(space.covering)}
    completed = False
    try:
        if cancelled and cancelled():
            return None
        if kind == "all":
            result["categories"] = _allocate_map((height, width), np.int32, directory, "categories.dat")
            result["granules"] = _allocate_map((height, width), np.int32, directory, "granules.dat")
        else:
            result["membership"] = _allocate_map((height, width), np.uint8, directory, "membership.dat")
        step = _tile_rows(width)
        valid_pixels = 0
        assigned_pixels = 0
        # Accumulate native-resolution class counts while each tile is in RAM.
        # Never rescan a full map on the Tk thread to build a legend.
        counts = None
        if kind == "all":
            categories = space.get_prototypes()
            granules = space.get_all_prototypes() if getattr(space, "is_granular", False) else categories
            counts = {"categories": np.zeros(len(categories), dtype=np.int64),
                      "granules": np.zeros(len(granules), dtype=np.int64)}
        operator = getattr(space, "tconorm", None)
        for start_y in range(y0, y1, step):
            if cancelled and cancelled():
                return None
            if getattr(space, "tconorm", None) != operator:
                # Never publish a map generated with two different aggregators.
                return None
            end_y = min(y1, start_y + step)
            tile = image.crop((x0, start_y, x1, end_y))
            valid = UtilsTools._get_alpha_values_from_pil(tile) > 0
            valid_pixels += int(np.count_nonzero(valid))
            if not np.any(valid):
                key_names = ("categories", "granules") if kind == "all" else ("membership",)
                for key in key_names:
                    result[key][start_y-y0:end_y-y0] = -1 if kind == "all" else 0
                if progress:
                    progress((end_y - y0) / height)
                continue
            if kind == "all":
                pair = manager.get_category_granule_label_maps(
                    tile, space, valid_mask=valid,
                    cancel_callback=cancelled)
                if pair is None:
                    return None
                result["categories"][start_y - y0:end_y - y0] = pair[0]
                result["granules"][start_y - y0:end_y - y0] = pair[1]
                for level, labels in zip(("categories", "granules"), pair):
                    # Transparent and unassigned pixels do not contribute to
                    # class counts; unassigned visible pixels stay in denominator.
                    assigned = labels[(labels >= 0) & valid]
                    counts[level] += np.bincount(assigned, minlength=len(counts[level]))
            else:
                single = manager.get_proto_percentage(
                    space.get_prototypes(), tile, space, int(selected[0]),
                    granule_index=selected[1], cancel_callback=cancelled,
                    return_coverage=True, valid_mask=valid)
                if single is None:
                    return None
                gray, covered, _ = single
                assigned_pixels += covered
                gray = np.asarray(gray, dtype=np.uint8)
                gray[~valid] = 0
                result["membership"][start_y - y0:end_y - y0] = gray
            if progress:
                progress((end_y - y0) / height)
        if (cancelled and cancelled()) or getattr(space, "tconorm", None) != operator:
            return None
        if kind == "single":
            result["coverage_threshold"] = 0.5
        if counts is not None:
            result["label_counts"] = {level: values.tolist() for level, values in counts.items()}
            assigned_pixels = int(counts["categories"].sum())
        result["valid_pixels"] = valid_pixels
        result["assigned_pixels"] = assigned_pixels
        result["coverage_percent"] = 100.0 * assigned_pixels / valid_pixels if valid_pixels else 0.0
        for key in ("categories", "granules", "membership"):
            if isinstance(result.get(key), np.memmap):
                result[key].flush()
        completed = True
        return result
    finally:
        if not completed:
            _dispose_mapping_result(result, None)


def render_result_tile(source_rgba, result, box, *, level="categories",
                       palette="original", style="color"):
    """Render a full-resolution RGBA tile, preserving source pixels outside ROI.

    `box` is in the *original* image coordinate system. No resampling occurs.
    """
    x0, y0, x1, y1 = map(int, box)
    base = np.asarray(source_rgba.crop(box).convert("RGBA"), dtype=np.uint8).copy()
    if result is None:
        return Image.fromarray(base, "RGBA")
    rx0, ry0, rx1, ry1 = result["scope"]
    left, top, right, bottom = max(x0, rx0), max(y0, ry0), min(x1, rx1), min(y1, ry1)
    if right <= left or bottom <= top:
        return Image.fromarray(base, "RGBA")
    yy0, yy1, xx0, xx1 = top-y0, bottom-y0, left-x0, right-x0
    source_region = base[yy0:yy1, xx0:xx1]
    sy0, sy1, sx0, sx1 = top-ry0, bottom-ry0, left-rx0, right-rx0
    if result["kind"] == "single":
        mu = np.asarray(result["membership"][sy0:sy1, sx0:sx1], dtype=np.uint8)
        if style == "gray":
            source_region[:, :, :3] = mu[:, :, None]
        else:
            source_region[:, :, :3] = np.clip(
                source_region[:, :, :3].astype(np.float32) *
                (mu.astype(np.float32) / 255.0)[..., None], 0, 255).astype(np.uint8)
    else:
        labels = np.asarray(result[level][sy0:sy1, sx0:sx1])
        colors = result["palettes"][level][palette]
        valid = (labels >= 0) & (labels < len(colors)) & (source_region[:, :, 3] > 0)
        if np.any(valid):
            source_region[valid, :3] = colors[labels[valid]]
        # Match Mapping All semantics: non-covering spaces retain unassigned
        # original pixels, while covering spaces leave them transparent.
        # Outside a selected ROI, the original image is always preserved.
        if result.get("covering", False):
            source_region[~valid, 3] = 0
    base[yy0:yy1, xx0:xx1] = source_region
    return Image.fromarray(base, "RGBA")


def _nearest_preview_indices(start, stop, count):
    """Use Pillow's own nearest-neighbour sampling, including its tie rules."""
    positions = np.arange(start, stop, dtype=np.int32).reshape(1, -1)
    return np.asarray(Image.fromarray(positions).resize(
        (count, 1), Image.Resampling.NEAREST))[0]


def render_workspace_preview(source, result, box, size, *, level="categories",
                             palette="original", style="color"):
    """Compose only displayed pixels; the full-resolution maps remain unchanged.

    Mapping previews are equivalent to rendering the native crop and then
    resizing it with NEAREST. No image colors or labels are interpolated.
    """
    if result is None:
        return source.resize(size, Image.Resampling.LANCZOS, box=box,
                             reducing_gap=3.0)
    x0, y0, x1, y1 = box
    xs = _nearest_preview_indices(x0, x1, size[0])
    ys = _nearest_preview_indices(y0, y1, size[1])
    preview = source.crop(box).resize(size, Image.Resampling.NEAREST)
    rx0, ry0, rx1, ry1 = result["scope"]
    ix = np.flatnonzero((xs >= rx0) & (xs < rx1))
    iy = np.flatnonzero((ys >= ry0) & (ys < ry1))
    if not ix.size or not iy.size:
        return preview
    key = "membership" if result["kind"] == "single" else level
    sampled = {"kind": result["kind"], "covering": result.get("covering", False),
               "scope": (int(ix[0]), int(iy[0]), int(ix[-1])+1, int(iy[-1])+1),
               key: result[key][np.ix_(ys[iy]-ry0, xs[ix]-rx0)]}
    if result["kind"] == "all":
        sampled["palettes"] = result["palettes"]
    return render_result_tile(preview, sampled, (0, 0, *size), level=level,
                              palette=palette, style=style)


def build_mapping_palettes(manager, space):
    proto = space.get_prototypes()
    flat = space.get_all_prototypes() if getattr(space, "is_granular", False) else proto
    category_original = manager.build_original_palette_uint8(proto, space.color_space)
    category_alt = manager.build_alt_palette_uint8(proto)
    granule_original = manager.build_original_palette_uint8(flat, space.color_space)
    granule_alt = manager.build_granule_alt_palette_uint8(space, category_alt)
    if getattr(space, "is_granular", False):
        offset = 0
        for i, category in enumerate(space.categories):
            count = len(category.prototypes)
            if count == 1:
                granule_alt[offset] = category_alt[i]
            offset += count
    return {"categories": {"original": category_original, "alt": category_alt},
            "granules": {"original": granule_original, "alt": granule_alt}}


def granule_and_category_entries(space):
    """Stable human labels and color choices, even for atomic spaces."""
    if space is None:
        return []
    granular = getattr(space, "is_granular", False)
    entries = []
    if granular:
        for ci, cat in enumerate(space.categories):
            entries.append((cat.label, (ci, None)))
            if len(cat.prototypes) > 1:
                for gi, p in enumerate(cat.prototypes):
                    entries.append((f"    {cat.label} / {p.label}", (ci, gi)))
    else:
        for ci, p in enumerate(space.get_prototypes()):
            entries.append((p.label, (ci, None)))
    return entries


def create_legend_image(labels, colors):
    font = ImageFont.load_default()
    width = max(240, max((len(str(s)) for s in labels), default=0) * 8 + 75)
    height = max(30, 14 + len(labels) * 30)
    image = Image.new("RGB", (width, height), "white")
    d = ImageDraw.Draw(image)
    for i, (label, col) in enumerate(zip(labels, colors)):
        y = 8 + i * 30
        d.rectangle((10, y, 32, y+21), fill=tuple(int(v) for v in col[:3]), outline="#777777")
        d.text((43, y+5), str(label), fill="#1d2939", font=font)
    return image


