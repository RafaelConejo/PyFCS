    def _set_zoom(self, zoom):
        if self._mapping_busy:
            return
        self._zoom = zoom
        if zoom is None:
            self._center = (self.original.width/2, self.original.height/2)
        self._render()

    def _zoom_factor(self, factor):
        zoom = self._zoom or self._fit_scale()
        self._set_zoom(max(0.025, min(32.0, zoom * factor)))

    def _fit_scale(self):
        width, height = max(10, self.canvas.winfo_width()-15), max(10, self.canvas.winfo_height()-15)
        return min(width/self.original.width, height/self.original.height)

    def _zoom_around(self, factor, x, y):
        if self._mapping_busy:
            return "break"
        pt = self._screen_to_image(x, y)
        if pt is None:
            return "break"
        old_scale = self._zoom or self._fit_scale()
        new_scale = max(0.025, min(32, old_scale * factor))
        # Maintain the source pixel beneath the cursor when zooming.
        w, h = self.canvas.winfo_width(), self.canvas.winfo_height()
        cx = pt[0] - (x - w/2) / new_scale
        cy = pt[1] - (y - h/2) / new_scale
        self._center = (cx, cy)
        self._zoom = new_scale
        self._render()
        return "break"

    def _wheel(self, event):
        return self._zoom_around(1.15 if event.delta > 0 else 1/1.15, event.x, event.y)

    def _view_geometry(self):
        width, height = max(2, self.canvas.winfo_width()), max(2, self.canvas.winfo_height())
        scale = self._zoom or self._fit_scale()
        cw = min(width, max(1, int(self.original.width * scale)))
        ch = min(height, max(1, int(self.original.height * scale)))
        # Crop from original only, at the current zoom, without producing a
        # full-resolution in-memory RGB copy on every pan.
        source_w = min(self.original.width, cw/scale)
        source_h = min(self.original.height, ch/scale)
        cx = min(max(self._center[0], source_w/2), self.original.width-source_w/2)
        cy = min(max(self._center[1], source_h/2), self.original.height-source_h/2)
        self._center = (cx, cy)
        left = max(0, min(self.original.width-source_w, cx-source_w/2))
        top = max(0, min(self.original.height-source_h, cy-source_h/2))
        right, bottom = left+source_w, top+source_h
        dx = (width-cw)//2
        dy = (height-ch)//2
        return (left, top, right, bottom), (dx, dy, cw, ch), scale

    def _screen_to_image(self, x, y):
        if self._display_bounds is None:
            return None
        crop, display = self._display_bounds
        left, top, right, bottom = crop
        dx, dy, cw, ch = display
        if not (dx <= x < dx+cw and dy <= y < dy+ch):
            return None
        ix = max(0, min(self.original.width-1, int(left+(x-dx)/cw*(right-left))))
        iy = max(0, min(self.original.height-1, int(top+(y-dy)/ch*(bottom-top))))
        return ix, iy

    def _image_to_screen(self, x, y):
        if self._display_bounds is None:
            return None
        (left, top, right, bottom), (dx, dy, cw, ch) = self._display_bounds
        return (dx+(x-left)*cw/(right-left), dy+(y-top)*ch/(bottom-top))

    def _schedule_render(self):
        if self._closed or self._view_after is not None:
            return
        self._view_after = self.win.after(45, self._scheduled_render)

    def _scheduled_render(self):
        self._view_after = None
        self._render()

    def _initial_render(self):
        self._initial_render_after = None
        self._render()

    def _render(self):
        if self._closed or not self.canvas.winfo_exists() or self.canvas.winfo_width() < 8:
            return
        crop, display, _ = self._view_geometry()
        dx, dy, cw, ch = display
        self._display_bounds = (crop, display)
        # Full source coordinates are mapped to the displayed rectangle.
        left, top, right, bottom = crop
        clip_box = (int(math.floor(left)), int(math.floor(top)),
                    min(self.original.width, int(math.ceil(right))),
                    min(self.original.height, int(math.ceil(bottom))))
        result = None if self._mapping_busy else self._visible_result()
        level = self.level_var.get().lower()
        palette = "alt" if self.palette_var.get() == "Alt. Colors" else "original"
        style = "gray" if self.single_style.get() == "Grayscale" else "color"
        signature = (self._job_id if result is not None else None, id(result),
                     clip_box, cw, ch, level if result and result["kind"] == "all" else None,
                     palette if result and result["kind"] == "all" else None,
                     style if result and result["kind"] == "single" else None,
                     self._mapping_busy)
        if signature != self._preview_signature or self._preview_item is None:
            view = render_workspace_preview(self.original, result, clip_box, (cw, ch),
                                            level=level, palette=palette, style=style)
            if self._mapping_busy:
                view = view.filter(ImageFilter.GaussianBlur(radius=3.0))
                view = Image.blend(view, Image.new("RGBA", view.size, "#eef2f7"), 0.14)
            self._preview = ImageTk.PhotoImage(view, master=self.canvas)
            if self._preview_item is None:
                self._preview_item = self.canvas.create_image(dx, dy, image=self._preview, anchor="nw")
            else:
                self.canvas.itemconfigure(self._preview_item, image=self._preview)
            self._preview_signature = signature
        self.canvas.coords(self._preview_item, dx, dy)
        self._draw_selection_overlay()
        self._draw_processing_overlay()
        text = (f"Full-resolution analysis · Zoom {(self._zoom or self._fit_scale())*100:.0f}% · "
                "Wheel: zoom · Right-drag: pan · Click: sample pixel · Drag: select ROI · F11: fullscreen")
        if self.view_status.get() != text:
            self.view_status.set(text)
        self._update_view_controls()

    def _draw_selection_overlay(self):
        """Selection marks do not invalidate or regenerate the photo image."""
        self.canvas.delete("roi", "selection")
        if self.roi:
            x0, y0, x1, y1 = self.roi
            a = self._image_to_screen(x0, y0)
            b = self._image_to_screen(x1, y1)
            if a and b:
                self.canvas.create_rectangle(*a, *b, outline="#d63d48", width=2, tags="roi")
        if self._mouse_start is not None and self._drag_rect:
            self.canvas.create_rectangle(*self._drag_rect, outline="#d63d48", width=2, dash=(3, 2), tags="selection")

    def _draw_processing_overlay(self):
        """Animate a small overlay without re-rendering the original image."""
        self.canvas.delete("workspace_processing")
        if not self._mapping_busy or self._closed or self._display_bounds is None:
            return
        _, (dx, dy, cw, ch) = self._display_bounds
        center_x, center_y = dx + cw / 2.0, dy + ch / 2.0
        self.canvas.create_rectangle(
            center_x - 98, center_y - 51, center_x + 98, center_y + 49,
            fill="white", outline=BORDER, width=1,
            tags="workspace_processing")
        self.canvas.create_arc(
            center_x - 17, center_y - 35, center_x + 17, center_y - 1,
            start=self._spinner_angle, extent=272,
            style="arc", width=4, outline="#526b87",
            tags="workspace_processing")
        self.canvas.create_text(
            center_x, center_y + 16,
            text=f"Processing… {self.progress_var.get():.0f}%",
            fill=TEXT, font=("Segoe UI", 9, "bold"),
            tags="workspace_processing")

    def _animate_processing(self):
        self._spinner_after = None
        if self._closed or not self._mapping_busy:
            return
        self._spinner_angle = (self._spinner_angle + 18) % 360
        self._draw_processing_overlay()
        try:
            self._spinner_after = self.win.after(80, self._animate_processing)
        except tk.TclError:
            self._spinner_after = None

    def _set_mapping_busy(self, busy):
        """On the Tk thread, lock viewport/options until a mapping job finishes."""
        self._mapping_busy = bool(busy)
        self._mouse_start = None
        self._drag_rect = None
        self._pan_start = None
        for widget in self._zoom_buttons + self._mapping_options_widgets:
            widget.configure(state="disabled" if busy else "normal")
        self.scope_combo.configure(state="disabled" if busy else "readonly")
        self.category_combo.configure(
            state="disabled" if busy or not self._entries else "readonly")
        for key, button in self.tconorm_buttons.items():
            button.configure(state="disabled" if busy or not getattr(
                self._space(), "is_granular", False) else "normal")
        self.run_button.configure(state="disabled" if busy else "normal")
        self.cancel_button.configure(state="normal" if busy else "disabled")
        self.canvas.configure(cursor="watch" if busy else "crosshair")
        if busy:
            self._spinner_angle = 0
            if self._spinner_after is None:
                self._animate_processing()
        elif self._spinner_after is not None:
            try:
                self.win.after_cancel(self._spinner_after)
            except tk.TclError:
                pass
            self._spinner_after = None
        self._update_view_controls()
        self._render()

    def _visible_result(self):
        if self._show_original_view:
            return None
        return self._result_for_current_mode()

    def _start_selection(self, event):
        if self._mapping_busy:
            return "break"
        pt = self._screen_to_image(event.x, event.y)
        self._mouse_start = (event.x, event.y, pt) if pt else None
        self._drag_rect = None

    def _move_selection(self, event):
        if self._mapping_busy:
            return "break"
        if self._mouse_start is None:
            return
        x, y, _ = self._mouse_start
        self._drag_rect = (x, y, event.x, event.y)
        self._draw_selection_overlay()

    def _end_selection(self, event):
        if self._mapping_busy:
            return "break"
        state = self._mouse_start
        self._mouse_start = None
        self._drag_rect = None
        self._draw_selection_overlay()
        if state is None:
            return
        sx, sy, pt = state
        end = self._screen_to_image(event.x, event.y)
        if not end:
            end = pt
        if abs(event.x-sx) < 4 and abs(event.y-sy) < 4:
            # A temporary inspection ROI is replaced by a point sample.
            # Preserve a processed region while inspecting pixels in its
            # result (including when temporarily showing the original image).
            if self.roi is not None and not self._has_processed_roi():
                self._reset_roi_selection()
            self._sample_pixel(pt)
        else:
            self.roi = _roi_box(*pt, *end, self.original.size)
            self._show_original_view = False
            self._sample_roi(self.roi)
        self._render()

    def _has_processed_roi(self):
        """Only a valid, completed regional mapping keeps its ROI on click."""
        if self.roi is None or self.scope_var.get() != "Selected ROI":
            return False
        result = self._result_for_current_mode()
        return result is not None and result.get("scope_mode") == "Selected ROI"

    def _reset_roi_selection(self):
        self._cancel_roi_sample()
        self.roi = None
        if self.scope_var.get() == "Selected ROI":
            self.scope_var.set("Full image")
        if self._result_for_current_mode() is None:
            self._show_original_view = False

    def _clear_roi(self):
        if self._mapping_busy:
            return
        self._reset_roi_selection()
        if self.sample is None:
            self._update_sample_ui()
        self._show_original_view = False
        self._render()

    def _pan_begin(self, event):
        if self._mapping_busy:
            return "break"
        self._pan_start = (event.x, event.y, *self._center)

    def _pan_motion(self, event):
        if self._mapping_busy:
            return "break"
        if not self._pan_start:
            return
        x, y, cx, cy = self._pan_start
        scale = self._zoom or self._fit_scale()
        self._center = (cx - (event.x-x)/scale, cy - (event.y-y)/scale)
        self._schedule_render()

    def _sample_pixel(self, point):
        self._cancel_roi_sample()
        rgb = self.original.getpixel(tuple(point))
        if rgb[3] == 0:
            self.sample = None
            self._update_sample_ui()
            self.progress_text.set("Transparent pixel · no color sample")
            return
        lab = UtilsTools.safe_lab_tuple(UtilsTools.analysis_rgb_to_lab(rgb[:3]))
        self.sample = {"coords": tuple(point), "roi": None, "rgb": tuple(rgb[:3]),
                       "lab": tuple(float(x) for x in lab), "name": "Image Pixel"}
        self._update_sample_ui()

    def _cancel_roi_sample(self):
        self._sample_token += 1
        if self._sample_cancel is not None:
            self._sample_cancel.set()
            self._sample_cancel = None

    def _sample_roi(self, box):
        self._cancel_roi_sample()
        if (box[2]-box[0]) * (box[3]-box[1]) <= 250_000:
            mean_lab, count, _ = UtilsTools.mean_lab_of_pil_roi(self.original, box)
            self._finish_roi_sample(box, mean_lab, count)
            return
        self.sample = None
        self._update_sample_ui()
        self.sample_text.set("Measuring ROI at original resolution…")
        token = self._sample_token
        cancel = self._sample_cancel = threading.Event()
        image, messages = self.original, self._sample_messages

        def work():
            # No Tk objects or model references in this worker. Cancellation
            # is checked between the same bounded source-row chunks as before.
            try:
                x0, y0, x1, y1 = box
                rows = max(1, 100000 // max(1, x1-x0))
                sums = np.zeros(3, dtype=np.float64)
                count = 0
                for y in range(y0, y1, rows):
                    if cancel.is_set():
                        return
                    mean, n, _ = UtilsTools.mean_lab_of_pil_roi(
                        image, (x0, y, x1, min(y1, y+rows)))
                    if n:
                        sums += mean*n
                        count += n
                if not cancel.is_set():
                    messages.put((token, box, sums/count if count else None, count, None))
            except Exception as exc:
                if not cancel.is_set():
                    messages.put((token, box, None, 0, str(exc)))

        try:
            threading.Thread(target=work, daemon=True, name="PyFCS-ROISample").start()
        except RuntimeError as exc:
            self._sample_cancel = None
            self.sample_text.set(f"Could not measure ROI: {exc}")

    def _poll_roi_samples(self):
        while not self._sample_messages.empty():
            token, box, lab, count, error = self._sample_messages.get_nowait()
            if token != self._sample_token or box != self.roi:
                continue
            self._sample_cancel = None
            if error is not None:
                self.sample_text.set(f"Could not measure ROI: {error}")
            else:
                self._finish_roi_sample(box, lab, count)

    def _finish_roi_sample(self, box, mean_lab, count):
        if not count:
            self.sample = None
            self._update_sample_ui()
            self.sample_text.set("ROI has no visible pixels")
            return
        lab = tuple(float(v) for v in mean_lab)
        rgb = tuple(int(v) for v in UtilsTools.lab_to_rgb(lab))
        self.sample = {"coords": ((box[0]+box[2]-1)//2, (box[1]+box[3]-1)//2),
                       "roi": box, "rgb": rgb, "lab": lab, "name": "Image ROI"}
        self._update_sample_ui()

    def _update_sample_ui(self):
        sample = self.sample
        if not sample:
            self.sample_text.set("Click a pixel or drag a region to inspect.")
            self.member_text.set("")
            self.sample_swatch.configure(bg="#c9ccd2")
            return
        rgb = sample["rgb"]
        lab = sample["lab"]
        self.sample_swatch.configure(bg=f"#{rgb[0]:02X}{rgb[1]:02X}{rgb[2]:02X}")
        scope_text = f"ROI: {sample['roi']}" if sample["roi"] else f"Pixel: {sample['coords']}"
        hex_color = f"#{rgb[0]:02X}{rgb[1]:02X}{rgb[2]:02X}"
        self.sample_text.set(
            f"{scope_text}\nRGB: {rgb[0]}, {rgb[1]}, {rgb[2]}"
            f"\nHEX: {hex_color}"
            f"\nLAB: {lab[0]:.2f}, {lab[1]:.2f}, {lab[2]:.2f}")
        space = self._space()
        if space is None:
            self.member_text.set("Load a color space to evaluate memberships.")
            return
        # A sampled RGB pixel must not travel RGB -> LAB -> RGB.
        use_rgb = sample["roi"] is None and space.color_space == "RGB"
        value, mode = (rgb, "RGB") if use_rgb else (lab, "LAB")
        memberships, winner, degree = mapping_membership_summary(space, value, mode)
        if winner is not None:
            self.member_text.set(f"Highest membership degree: {winner}  ·  μ = {degree:.4f}")
        else:
            self.member_text.set("Outside fuzzy support · no category assignment")

